void main() {
  int angka1 = 20;
  int angka2 = 5;

  int hasilTambah = angka1 + angka2;
  int hasilKurang = angka1 - angka2;
  int hasilKali = angka1 * angka2;
  double hasilBagi = angka1 / angka2;

  print('=== OPERASI ARITMATIKA ===');
  print('Penjumlahan ($angka1 + $angka2) = $hasilTambah');
  print('Pengurangan ($angka1 - $angka2) = $hasilKurang');
  print('Perkalian ($angka1 * $angka2)   = $hasilKali');
  print('Pembagian ($angka1 / $angka2)   = $hasilBagi');
}
